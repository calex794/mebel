"""Readable Latin URLs for Russian titles entered in the admin panel."""
import re

from django.utils.text import slugify

MAP = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e",
    "ё": "e", "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k",
    "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
    "с": "s", "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "ts",
    "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "", "ы": "y", "ь": "",
    "э": "e", "ю": "yu", "я": "ya",
}


def latin_slug(title):
    text = "".join(MAP.get(ch, ch) for ch in title.lower())
    result = slugify(text)[:160].strip("-")
    return result or "material"
